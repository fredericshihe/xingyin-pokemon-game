import { MONSTERS } from '../src/utils/gameData.js'

const byId = new Map(MONSTERS.map((m) => [m.id, m]))
const byDex = new Map(MONSTERS.map((m) => [m.pokedexId, m]))

console.log('=== 当前游戏宝可梦总数:', MONSTERS.length, '===')

// 内部ID情况
const ids = MONSTERS.map(m => m.id).sort((a,b)=>a-b)
const idGaps = []
for (let i=1;i<=Math.max(...ids);i++) if(!byId.has(i)) idGaps.push(i)
console.log('内部ID范围: 1 ~', Math.max(...ids), '| 缺口:', idGaps.join(', ') || '无')

// pokedexId 覆盖：哪些初代(1-151)已有，哪些缺
const presentDex = new Set(MONSTERS.map(m => m.pokedexId).filter(d => d>=1 && d<=151))
const missingDex = []
for (let d=1; d<=151; d++) if(!presentDex.has(d)) missingDex.push(d)
console.log('\n=== 初代151覆盖情况 ===')
console.log('已涵盖初代图鉴编号:', presentDex.size, '/ 151')
console.log('缺失的初代图鉴编号 (', missingDex.length, '个):', missingDex.join(', '))

// 非初代的宝可梦（pokedexId>151）——这些是游戏额外加的
const nonGen1 = MONSTERS.filter(m => m.pokedexId > 151).sort((a,b)=>a.pokedexId-b.pokedexId)
console.log('\n=== 游戏中的非初代宝可梦 (', nonGen1.length, '只) ===')
nonGen1.forEach(m => console.log(`  内部id:${String(m.id).padStart(3)} dex:${String(m.pokedexId).padStart(3)} ${m.name} (${[m.type,m.type2].filter(Boolean).join('/')})`))

