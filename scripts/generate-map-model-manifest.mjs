import fs from 'node:fs/promises'
import path from 'node:path'
import { MAP_CHAIN, getMapInfo } from '../src/game/data/mapCatalog.js'

const CORE_MODEL_KEYS = new Set([
  'grass',
  'grassLarge',
  'bush',
  'treeOak',
  'treeDefault',
  'treePine',
  'rock',
  'stone',
  'flowerYellow',
  'flowerRed',
  'mushroom',
  'campfire',
  'tent',
  'sign'
])

const getDecorativeModelKey = (type) => {
  switch (type) {
    case 'tent': return 'tent'
    case 'campfire': return 'campfire'
    case 'sign': return 'sign'
    case 'tree-oak': return 'treeOak'
    case 'tree-default': return 'treeDefault'
    case 'tree-pine': return 'treePine'
    case 'bush-large': return 'bush'
    case 'rock-large': return 'rock'
    case 'stone-large': return 'stone'
    case 'grass-small': return 'grass'
    case 'grass-large': return 'grassLarge'
    case 'flower-yellow': return 'flowerYellow'
    case 'flower-red': return 'flowerRed'
    case 'mushroom-red': return 'mushroom'
    case 'wetland_reed_clump': return 'wetlandReedClump'
    case 'shore_dock_small': return 'shoreDockSmall'
    case 'shore_rowboat': return 'shoreRowboat'
    case 'town_fence_low': return 'townFenceLow'
    case 'town_stall_green': return 'townStallGreen'
    case 'farm_cart_high': return 'farmCartHigh'
    case 'grave_lantern_glass': return 'graveLanternGlass'
    case 'grave_iron_fence_broken': return 'graveIronFenceBroken'
    case 'ridge_block_grass_edge': return 'ridgeBlockGrassEdge'
    case 'mine_crate_strong': return 'mineCrateStrong'
    case 'mine_control_lever': return 'mineControlLever'
    default: return type
  }
}

const getRequiredModelKeys = (mapInfo) => {
  const keys = new Set(CORE_MODEL_KEYS)
  mapInfo?.decorativeObjects?.forEach((object) => {
    const key = getDecorativeModelKey(object.type)
    if (key) keys.add(key)
  })
  return [...keys]
}

const manifest = Object.fromEntries(
  MAP_CHAIN.map((mapName) => {
    const mapInfo = getMapInfo(mapName)
    if (!mapInfo || mapInfo.renderMode !== 'three-lowpoly') {
      return [mapName, { modelKeys: [] }]
    }
    return [mapName, { modelKeys: getRequiredModelKeys(mapInfo) }]
  })
)

const output = `/** Auto-generated by scripts/generate-map-model-manifest.mjs — do not edit manually. */
export const MAP_MODEL_MANIFEST = ${JSON.stringify(manifest, null, 2)}
`

await fs.writeFile(
  path.join(process.cwd(), 'src/game/data/mapModelManifest.generated.js'),
  output,
  'utf8'
)

console.log(JSON.stringify({
  maps: Object.keys(manifest).length,
  sample: manifest.GodotMap?.modelKeys?.length || 0
}, null, 2))
