// 统计每个模型在各地图里（统一之前）的渲染尺寸，确定统一使用的标准尺寸。
// 运行：npm run generate:model-scales
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

process.env.SKIP_MODEL_SCALE_NORMALIZATION = '1'
const { MAP_CATALOG, MAP_CHAIN } = await import('../src/game/data/mapCatalog.js')
const { THEME_LANDMARK_SCALES } = await import('../src/game/data/godotMaps/godot_region_maps.js')
const norm = await import('../src/game/mapModelScaleNormalization.js')
const { getTreeModelScale, TREE_CATALOG_MODEL_KEYS } = await import('../src/game/modelScaleReference.js')

const median = (values) => {
  const sorted = [...values].sort((a, b) => a - b)
  const mid = Math.floor(sorted.length / 2)
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2
}

const perKey = new Map()
for (const id of MAP_CHAIN) {
  const map = MAP_CATALOG[id]?.mapInfo
  for (const object of map?.decorativeObjects || []) {
    if (!norm.isScaleNormalizable(object)) continue
    const key = norm.getModelKeyForObject(object)
    if (!key || norm.PROCEDURAL_MODEL_SCALES[key] != null) continue
    const scale = norm.getRenderedObjectScale(object, THEME_LANDMARK_SCALES)
    if (!(scale > 0)) continue
    const maps = perKey.get(key) || new Map()
    const list = maps.get(id) || []
    list.push(scale)
    maps.set(id, list)
    perKey.set(key, maps)
  }
}

const { MAP_ASSET_CATALOG } = await import('../src/game/data/mapAssetCatalog.js')
// 标准尺寸：建筑类 地标尺寸 > defaultScale > 实际用法（和实际差太多的设计值不用）；自然景物取设计尺寸与实际用法中较小者。
// 取偏小的一侧：偏大的自然景物会换成一簇标准尺寸（保留覆盖），而偏小的放大常常放不下。
const entries = [...perKey.entries()]
  .map(([key, maps]) => {
    const mapMedians = [...maps.values()].map(median)
    const landmark = THEME_LANDMARK_SCALES[key]
    const designed = MAP_ASSET_CATALOG[key]?.defaultScale
    const observed = median(mapMedians)
    // 建筑类的 defaultScale 常常和实际用法对不上（例如道馆专属建筑全图都用 3 倍），
    // 此时以实际用法为准；自然景物保持设计尺寸，偏大的会拆成一簇。
    const agrees = (value, limit) => value != null && observed / value <= limit && value / observed <= limit
    // 自然景物取设计尺寸和实际用法中较小的：偏大的拆成一簇，偏小的放大常常放不下
    const canonical = getTreeModelScale(key) ?? (norm.isNaturalModelName(key)
      ? Math.min(designed ?? landmark ?? observed, observed)
      : agrees(landmark, 1.3) ? landmark : agrees(designed, 1.5) ? designed : observed)
    return [key, Number(canonical.toFixed(3)), Number(median(mapMedians).toFixed(3))]
  })
  .sort(([a], [b]) => a.localeCompare(b))

// Event trees are protected from layout normalization, but share the same
// measured species size as decorative and procedural forest trees.
for (const key of TREE_CATALOG_MODEL_KEYS) {
  if (entries.some(([entryKey]) => entryKey === key)) continue
  const scale = getTreeModelScale(key)
  if (scale != null) entries.push([key, scale, scale])
}
entries.sort(([a], [b]) => a.localeCompare(b))

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const out = path.join(root, 'src/game/data/modelCanonicalScales.generated.js')
writeFileSync(out, `// Generated by scripts/generate-model-canonical-scales.mjs — do not edit by hand.
// 每个模型统一使用的渲染尺寸（规则见生成脚本）。程序化林地模型见 PROCEDURAL_MODEL_SCALES。
export const MODEL_CANONICAL_SCALES = {
${entries.map(([key, value, observed]) => `  ${JSON.stringify(key)}: ${value},${observed !== value ? ` // 统一前各地图中位数 ${observed}` : ''}`).join('\n')}
}
`)
console.log(`wrote ${entries.length} canonical model scales -> ${path.relative(root, out)}`)
