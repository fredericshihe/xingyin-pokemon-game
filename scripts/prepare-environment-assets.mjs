import fs from 'node:fs/promises'
import { NodeIO, getBounds } from '@gltf-transform/core'
import { ALL_EXTENSIONS } from '@gltf-transform/extensions'
import { dedup, weld, draco } from '@gltf-transform/functions'
import draco3d from 'draco3dgltf'
import { withViteAuditServer } from './load-vite-module.mjs'

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
  'draco3d.decoder': await draco3d.createDecoderModule(),
  'draco3d.encoder': await draco3d.createEncoderModule()
})
await withViteAuditServer(async ({ loadModule }) => {
  const { MAP_ASSET_CATALOG } = await loadModule('/src/game/data/mapAssetCatalog.js')
  const { MAP_ENVIRONMENT_ANCHORS } = await loadModule('/src/game/data/mapEnvironmentDesign.js')
  const { MAP_ENVIRONMENT_VIGNETTES } = await loadModule('/src/game/data/mapEnvironmentVignettes.js')
  const keys = new Set(Object.values(MAP_ENVIRONMENT_ANCHORS).flatMap(objects => objects.map(object => object.type)))
  const sceneTypes = new Set(Object.values(MAP_ENVIRONMENT_VIGNETTES).flatMap(scenes => scenes.flatMap(scene => scene.props.map(prop => prop.type))))
  for (const type of sceneTypes) keys.add(type)
  keys.add('nature_tree_pine')
  keys.add('town_tree')
  for (const type of ['grave_gravestone_round', 'grave_gravestone_broken', 'grave_gravestone_cross', 'grave_cross_wood']) keys.add(type)
  const footprints = {}, measurements = {}, manifest = []
  for (const key of [...keys].sort()) {
    const asset = MAP_ASSET_CATALOG[key]
    const file = `public${asset.assetPath}`
    let doc = await io.read(file)
    if (key.startsWith('environment_') && !doc.getRoot().listExtensionsUsed().some(ext => ext.extensionName === 'KHR_draco_mesh_compression')) {
      await doc.transform(dedup(), weld(), draco({ quantizePosition: 14, quantizeNormal: 12, quantizeColor: 8 }))
      await io.write(file, doc)
      doc = await io.read(file)
    }
    const root = doc.getRoot(), bounds = getBounds(root.listScenes()[0])
    // Model origins need not be centred. Symmetric clearance must enclose both sides.
    footprints[key] = {
      width: Math.ceil(Math.max(Math.abs(bounds.min[0]), Math.abs(bounds.max[0])) * 2 / 1.55 * 100) / 100,
      height: Math.ceil(Math.max(Math.abs(bounds.min[2]), Math.abs(bounds.max[2])) * 2 / 1.55 * 100) / 100
    }
    if (sceneTypes.has(key)) measurements[key] = { footprint: footprints[key], height: bounds.max[1] - bounds.min[1] }
    if (asset.assetPath.includes('/xingyin-environment-v1/')) manifest.push({
      key, file: asset.assetPath, bytes: (await fs.stat(file)).size, bounds,
      triangles: root.listMeshes().reduce((sum, m) => sum + m.listPrimitives().reduce((n, p) => n + p.getIndices().getCount() / 3, 0), 0)
    })
  }
  await fs.writeFile('src/game/data/environmentSceneryMeasurements.generated.js', `// Measured GLB bounds, regenerated by npm run environment:prepare.\nexport const ENVIRONMENT_SCENERY_MEASUREMENTS = ${JSON.stringify(measurements, null, 2)}\n`)
  await fs.writeFile('src/game/data/environmentModelFootprints.generated.js', `// GLB bounds / 1.55 metres per tile. Run npm run environment:prepare after re-export.\nexport const ENVIRONMENT_MODEL_FOOTPRINTS = ${JSON.stringify(footprints, null, 2)}\n`)
  await fs.writeFile('public/assets/3d/xingyin-environment-v1/manifest.json', JSON.stringify(manifest, null, 2) + '\n')
  console.log(`${keys.size} measured footprints; ${manifest.length} original models, ${manifest.reduce((sum, a) => sum + a.bytes, 0)} bytes.`)
})
