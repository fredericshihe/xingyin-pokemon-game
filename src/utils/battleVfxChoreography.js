// Zero-based hit number is supplied by the battle result. It never creates hits.
export function getContactPlacement(motion, hitIndex = 0) {
  const n = Math.max(0, Math.floor(hitIndex))
  if (motion === 'flank') {
    const positions = [[-.58,-.3, .4],[.5,.2,2.9],[-.28,.48,-.8],[.35,-.5,2],[-.6,.1,-.2]]
    return positions[n % positions.length]
  }
  if (motion === 'alternating') return [n % 2 ? .28 : -.28, .15 - (n % 3) * .18, n % 2 ? .42 : -.42]
  if (motion === 'low') return [.1,.56,-.7]
  if (motion === 'overhead') return [0,-.12,0]
  if (motion === 'diagonal') return [.12,0,-.55]
  return [0,0,0]
}
